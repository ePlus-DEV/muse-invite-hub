/* Trusted main-only Issue comment handler. Feedback never edits public code status. */
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { issueCodes, issueMarker, originalIssueNumber, withCanonicalIssueRefs, REPO } from "./code-issue-map.mjs";
import { readCatalog } from "./catalog.mjs";

const ACK_MARKER = "<!-- muse-code-feedback-reopened -->";

export function feedbackCodeForIssue(issue, catalog, commentBody="") {
  if (!issue || issue.pull_request || !Number.isSafeInteger(issue.number)) return null;
  const codes = issueCodes(issue);
  // A multi-code Issue may be the canonical thread for several separate
  // listings. Prefer the explicitly named code in the user's feedback.
  const requested = /^Code:\s*([A-Z0-9-]{4,32})\s*$/mi.exec(commentBody)?.[1];
  const ordered = requested && codes.includes(requested)
    ? [requested,...codes.filter(code=>code!==requested)] : codes;
  for (const code of ordered) {
    const item = catalog.find(entry=>entry.code===code);
    if (!item) continue;
    const canonicalNumber = originalIssueNumber(item);
    if (canonicalNumber !== null) {
      if (canonicalNumber===issue.number) return code;
      continue;
    }
    if (String(issue.body || "").includes(issueMarker(code)) ||
        String(issue.body || "").includes("<!-- muse-code-feedback-root:" + code + " -->")) return code;
  }
  return null;
}

// A pasted referral for a DIFFERENT code is a new submission, not feedback
// on this canonical Issue. Only classify explicit stand-alone code labels
// accompanied by the official Muse join link; ambiguous replies stay pending.
export function unrelatedReferralCode(body, canonicalCodes) {
  if (typeof body !== "string" || body.length > 3500 ||
      !Array.isArray(canonicalCodes) || !canonicalCodes.length ||
      !/https:\/\/muse\.ai\/join(?:[/?#]|\s|$)/i.test(body)) return null;
  const labels=[...body.matchAll(/^[ \t]*(?:邀请码|邀请代码|Invite\s+code|Code|C[oó]digo|Mã\s*mời)\s*[:：]\s*([A-Z0-9]{6})[ \t]*$/gimu)];
  if (labels.length !== 1) return null;
  const candidate=labels[0][1].toUpperCase();
  if (canonicalCodes.some(code=>code.toUpperCase()===candidate ||
      new RegExp("(^|[^A-Z0-9])"+code+"([^A-Z0-9]|$)","i").test(body))) return null;
  return candidate;
}

const PUBLIC_CODE=/^[A-Z0-9]{6}$/;
const CANDIDATE="muse-comment-referral-candidate";

// A candidate is a tracking Issue only. Never treat it as an authorized Share
// Code Issue or a substitute for the contributor's own checked confirmations.
export function referralIssueMatches(issues, code) {
  if (!PUBLIC_CODE.test(code) || !Array.isArray(issues)) throw Error("Invalid candidate lookup");
  const marker="<!-- "+CANDIDATE+":"+code+" -->";
  return issues.filter(issue=>!issue.pull_request &&
    (issueCodes(issue).includes(code) ||
      String(issue.body||"").includes(marker) ||
      new RegExp("^\\[(?:Invite|Invite candidate)\\]\\s+"+code+"(?:\\b|$)","i")
        .test(String(issue.title||""))));
}

async function allRepositoryIssues(api) {
  const issues=[];
  for(let page=1;page<=10;page++) {
    const batch=await api("GET","issues?state=all&per_page=100&page="+page);
    if(!Array.isArray(batch)) throw Error("Expected GitHub Issues page");
    issues.push(...batch);
    if(batch.length<100) return issues;
  }
  // Do not create a possibly duplicate candidate with incomplete history.
  throw Error("Issue inventory exceeded safe deduplication limit");
}

function candidateIssueBody(code,comment,issueNumber) {
  const origin="https://github.com/"+REPO+"/issues/"+issueNumber+
    "#issuecomment-"+comment.id;
  return [
    "<!-- "+CANDIDATE+":"+code+" -->",
    "## Unverified comment referral — "+code,
    "",
    "Detected from [@"+comment.user.login+"'s comment]("+origin+
      ") on Issue #"+issueNumber+".",
    "",
    "**Code:** "+code,
    "**Original GitHub commenter:** @"+comment.user.login+
      " (user ID "+comment.user.id+")",
    "**Status:** Pending the commenter's own public-sharing and privacy confirmations",
    "",
    "The source comment contains a Muse join link, which is **not proof of code ownership**.",
    "This tracking Issue was generated by a bot; it is not a submitted Share Code form,",
    "and its author must not be treated as the code owner.",
    "",
    "@"+comment.user.login+": to submit this code for review, use the "+
      "[Share Code form](https://github.com/"+REPO+
      "/issues/new?template=share-code.yml), select the real source "+
      "and personally check both required confirmations if true.",
    "",
    "Do not generate a catalog PR or claim a Muse redemption from this candidate.",
    "If a verified submission already exists, link it here and close this tracking Issue through normal review."
  ].join("\n");
}

export function shouldReopen(issue, comment, catalog) {
  if (!comment || !Number.isSafeInteger(comment.id) ||
      !comment.body?.trim() || !comment.user?.login ||
      comment.user.type === "Bot" ||
      comment.user.login.endsWith("[bot]") || comment.user.login === "eplus-bot") return false;
  return issue?.state === "closed" && Boolean(feedbackCodeForIssue(issue, catalog)) &&
    !unrelatedReferralCode(comment.body,issueCodes(issue));
}

async function github(method, path, token, body, request=fetch) {
  const response = await request("https://api.github.com/repos/" + REPO + "/" + path, {
    method,
    headers: {
      Authorization: "Bearer " + token,
      Accept: "application/vnd.github+json",
      "X-GitHub-Api-Version": "2022-11-28",
      ...(body === undefined ? {} : { "Content-Type": "application/json" })
    },
    ...(body === undefined ? {} : {body: JSON.stringify(body)}),
    signal: AbortSignal.timeout(25000)
  });
  if (!response.ok) throw Error("GitHub " + method + " " + path + ": HTTP " + response.status);
  return response.status === 204 ? null : response.json();
}

export async function reopenOnFeedback({
  repository=process.env.GITHUB_REPOSITORY,
  token=process.env.GH_TOKEN,
  issueNumber=Number(process.env.ISSUE_NUMBER),
  commentId=Number(process.env.COMMENT_ID),
  request=fetch,
  catalog
} = {}) {
  if (repository !== REPO || !token ||
      !Number.isSafeInteger(issueNumber) || issueNumber <= 0 ||
      !Number.isSafeInteger(commentId) || commentId <= 0) {
    throw Error("Trusted repository, token, issue and comment identifiers required");
  }
  const api=(method,path,body)=>github(method,path,token,body,request);
  const rawEntries = catalog ?? readCatalog();
  const roots = catalog ? {} : JSON.parse(readFileSync(new URL("../data/code-issues.json", import.meta.url), "utf8"));
  const entries = withCanonicalIssueRefs(rawEntries, roots);
  const issue = await api("GET", "issues/" + issueNumber);
  const comment = await api("GET", "issues/comments/" + commentId);
  if (comment.issue_url?.split("/").at(-1) !== String(issueNumber)) {
    return {outcome:"ignored",reason:"Comment does not belong to this Issue."};
  }
  const human=comment?.user?.login && comment.user.type!=="Bot" &&
    !comment.user.login.endsWith("[bot]") && comment.user.login!=="eplus-bot";
  const foreign=human ? unrelatedReferralCode(comment.body,issueCodes(issue)) : null;
  if (foreign && feedbackCodeForIssue(issue,entries)) {
    const marker="<!-- muse-unrelated-referral:"+commentId+" -->";
    const comments=await api("GET","issues/"+issueNumber+"/comments?per_page=100");
    if (comments.some(row=>["github-actions[bot]","eplus-bot"].includes(row.user?.login) &&
        String(row.body||"").includes(marker))) {
      return {outcome:"already-notified",issueNumber,code:foreign};
    }

    const published=entries.find(entry=>entry.code===foreign);
    let candidateIssue=null;
    let existingCount=0;
    if (!published) {
      const issues=await allRepositoryIssues(api);
      const matches=referralIssueMatches(issues,foreign);
      existingCount=matches.length;
      if (matches.length===1) candidateIssue=matches[0];
      if (matches.length===0) {
        // Bound accidental or abusive intake: at most three outstanding
        // comment-sourced candidate Issues per commenter.
        const createdByUser=issues.filter(row=>!row.pull_request &&
          row.state==="open" && String(row.body||"").includes(
            "Original GitHub commenter:** @"+comment.user.login+
            " (user ID "+comment.user.id+")") &&
          String(row.body||"").includes("<!-- "+CANDIDATE+":"));
        if (createdByUser.length<3) {
          candidateIssue=await api("POST","issues",{
            title:"[Invite candidate] "+foreign+" — confirmation required",
            body:candidateIssueBody(foreign,comment,issueNumber)
          });
          if (!Number.isSafeInteger(candidateIssue?.number)) {
            throw Error("GitHub did not confirm new candidate Issue");
          }
        }
      }
    }
    const newLink=candidateIssue
      ? "Existing tracking [Issue #"+candidateIssue.number+"](https://github.com/"+
          REPO+"/issues/"+candidateIssue.number+") "+(existingCount?"already tracks":"now tracks")+
          " this code. "
      : existingCount>1
        ? "Multiple Issues already mention this code; review duplicates before taking action. "
        : "No tracking Issue was created because the per-user safety limit was reached. ";
    const message=published
      ? "ℹ️ **"+foreign+"** is already listed at https://muse.eplus.dev/codes/"+
          foreign+"/ . Please post feedback in its own canonical Issue."
      : "ℹ️ **"+foreign+"** is a different invite from the code in this Issue. "+
        newLink+"This is **not an accepted submission**. @"+comment.user.login+
        ", please use the [Share Code form](https://github.com/"+REPO+
        "/issues/new?template=share-code.yml) and personally provide the required "+
        "ownership/public-sharing and privacy confirmations. No catalog PR was created.";
    await api("POST","issues/"+issueNumber+"/comments",
      {body:marker+"\n"+message});
    return {outcome:"redirected",issueNumber,code:foreign,
      candidateIssueNumber:candidateIssue?.number||null,published:Boolean(published)};
  }
  if (!shouldReopen(issue, comment, entries)) {
    console.log("No action: not new community feedback on a closed canonical code Issue.");
    return { outcome:"ignored" };
  }
  const code = feedbackCodeForIssue(issue, entries, comment.body);
  // Marker prevents the older accepted-Issue reconciler from closing the
  // reopened feedback thread during the next Pages deployment.
  const note = ACK_MARKER + "\nNew community feedback for **" + code +
    "** by @" + comment.user.login + " has been received. Reopening this existing " +
    "Issue for maintainer review. A comment is **not** verification by Muse.";
  const comments = await api("GET", "issues/" + issueNumber + "/comments?per_page=100");
  if (!comments.some(x => x.user?.login === "github-actions[bot]" &&
       x.body?.includes(ACK_MARKER))) {
    await api("POST", "issues/" + issueNumber + "/comments", {body:note});
  }
  await api("PATCH", "issues/" + issueNumber, {state:"open"});
  console.log("Reopened original Issue #" + issueNumber + " for " + code);
  return { outcome:"reopened", issueNumber, code };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await reopenOnFeedback();
}
