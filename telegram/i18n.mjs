export function normalizeLocale(value) {
  if(typeof value!=="string")return "en";
  const code=value.trim().toLowerCase().replace(/_/g,"-").split("-")[0];
  return LOCALES.includes(code)?code:"en";
}
export function tr(locale,key,params={}) {
  const language=normalizeLocale(locale);
  const value=STRINGS[language][key]??STRINGS.en[key];
  if(typeof value!=="string")throw Error("Missing Telegram translation: "+key);
  return value.replace(/\{([a-zA-Z]+)\}/g,(_,name)=>String(params[name]??"{"+name+"}"));
}
export function menuText(locale,key) {
  const value=MENU_TEXT[normalizeLocale(locale)][key];
  if(!value)throw Error("Unknown Telegram menu item "+key);
  return value;
}
